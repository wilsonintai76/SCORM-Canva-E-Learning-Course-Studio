export function createBrandedIconSvgDataUrl(
  iconKey: BrandedIconKey,
  primaryColor = '#2563eb',
  accentColor = '#06b6d4',
  surfaceColor = '#0f172a'
): string {
  const pathMarkup = ICON_PATHS[iconKey] || ICON_PATHS.shield;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 96 96" data-branded-icon="${iconKey}">
  <defs>
    <linearGradient id="bgGrad_${iconKey}" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0%" stop-color="${surfaceColor}" />
      <stop offset="100%" stop-color="${primaryColor}" stop-opacity="0.28" />
    </linearGradient>
  </defs>
  <rect x="4" y="4" width="88" height="88" rx="22" fill="url(#bgGrad_${iconKey})" stroke="${primaryColor}" stroke-width="3"/>
  <circle cx="48" cy="48" r="28" fill="${primaryColor}" fill-opacity="0.16"/>
  <g transform="translate(24, 24) scale(2)" fill="none" stroke="${accentColor}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" color="${accentColor}">
    ${pathMarkup}
  </g>
</svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

export function extractBrandedIconKey(url: string): BrandedIconKey | null {
  try {
    const decoded = decodeURIComponent(url);
    const match = decoded.match(/data-branded-icon="([a-z]+)"/);
    if (match && match[1] in ICON_PATHS) {
      return match[1] as BrandedIconKey;
    }
  } catch {
    // ignore malformed URI
  }
  return null;
}

export function applyBrandTokensToResourceNodes(
  nodes: CanvasNode[],
  theme?: GlobalTheme
): CanvasNode[] {
  if (!theme) return nodes;
  const primary = theme.primaryColor || '#2563eb';
  const accent = theme.accentColor || '#06b6d4';
  const surface = theme.surfaceColor || theme.backgroundColor || '#0f172a';
  const font = theme.bodyFontFamily || theme.fontFamily || 'Inter, sans-serif';

  return nodes.map((node) => {
    const cloned: CanvasNode = JSON.parse(JSON.stringify(node));
    if (cloned.type === 'image' && cloned.url) {
      const iconKey = extractBrandedIconKey(cloned.url);
      if (iconKey) {
        cloned.url = createBrandedIconSvgDataUrl(iconKey, primary, accent, surface);
      }
    } else if (cloned.type === 'shape') {
      if (cloned.fill && !['transparent', '#0f172a', '#1e293b', '#020617'].includes(cloned.fill.toLowerCase())) {
        cloned.fill = primary;
      }
      if (cloned.stroke && !['transparent', '#334155', '#1e293b'].includes(cloned.stroke.toLowerCase())) {
        cloned.stroke = accent;
      }
    } else if (cloned.type === 'text') {
      cloned.fontFamily = font;
    } else if (cloned.type === 'quiz') {
      cloned.themeColor = primary;
    }
    return cloned;
  });
}

